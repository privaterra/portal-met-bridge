#!/usr/bin/env node
// vendor.mjs — the third-party code the app ships (vendor/), kept current and accounted for.
//
// The app has no build step: the five libraries it uses are copied into vendor/ from
// their npm packages, byte for byte. This tool is the only thing that writes them, and
// vendor/manifest.json records what each file is (package, version, the file inside
// the package, its SHA-256), so a library can never change or go stale unnoticed.
//
//   node tools/vendor.mjs verify            offline: every vendored file is the one the manifest names
//   node tools/vendor.mjs check             verify + newer versions on npm + security advisories for
//                                           the versions shipped (and, as a note, for the dev tools)
//   node tools/vendor.mjs update            fetch the latest version of every library into vendor/
//   node tools/vendor.mjs update jspdf      …of one library;  --to 4.2.1 for a specific version;
//                                           --no-major to stay within the current major version
//   node tools/vendor.mjs sources           what changed in the projects the app's protocol knowledge comes
//                                           from (vendor/sources.json) since they were last read; --record marks them read
//
// Options for check:  --level low|moderate|high|critical   fail on advisories of at least this severity (default low: any)
//                     --fail-outdated                      also fail when a newer version exists
//                     --json                               print the report as JSON
//                     --summary <file>                     append the report as Markdown (GitHub's $GITHUB_STEP_SUMMARY)
// Exit codes: 0 fine · 1 a vendored file is wrong, or an advisory needs attention · 2 could not reach npm · 3 outdated (--fail-outdated)
//
// Advisories come from npm's database (the GitHub Advisory Database) through `npm audit`,
// run against exactly the versions in the manifest. One that does not apply to how the app
// uses the library can be accepted, with a reason and an end date, in
// vendor/advisories-accepted.json — it is then listed as accepted instead of failing.
//
// Needs Node 18+, npm and tar on the PATH (all three come with Node on macOS and Linux).

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, appendFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendorDir = join(root, 'vendor');
const manifestPath = join(vendorDir, 'manifest.json');
const acceptedPath = join(vendorDir, 'advisories-accepted.json');
const sourcesPath = join(vendorDir, 'sources.json');
const SEVERITIES = ['info', 'low', 'moderate', 'high', 'critical'];
const NPM = process.platform === 'win32' ? 'npm.cmd' : 'npm';

export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
export const loadManifest = () => JSON.parse(readFileSync(manifestPath, 'utf8'));
const saveManifest = (m) => writeFileSync(manifestPath, JSON.stringify(m, null, 2) + '\n');

/** vendor/package.json: the same versions as a manifest GitHub's dependency graph (and so Dependabot alerts) can read. */
export function vendorPackageJson(manifest) {
  return {
    name: 'portal-met-bridge-vendor',
    private: true,
    type: 'module', // the files beside it are ES modules (the tests import them under Node)
    description: 'Generated by tools/vendor.mjs from vendor/manifest.json — do not edit. Lists the libraries copied into this folder so that GitHub (Dependabot alerts) and `npm audit` can see them; nothing is installed from it.',
    dependencies: Object.fromEntries(Object.entries(manifest.packages).map(([name, p]) => [name, p.version])),
  };
}

/** The line in README.md's file listing that names the vendored versions. */
export function readmeVendorLine(manifest) {
  const list = Object.entries(manifest.packages).map(([name, p]) => `${p.label || name} ${p.version}`).join(', ');
  const licenses = [...new Set(Object.values(manifest.packages).map((p) => p.license))];
  return `vendor/                      ${list} (${licenses.length === 1 ? `all ${licenses[0]}` : licenses.join(', ')}; versions and checksums in vendor/manifest.json)`;
}

/** Offline check. Returns a list of problems; empty means vendor/ is exactly what the manifest says. */
export function verify(manifest = loadManifest()) {
  const problems = [];
  const expected = new Set(['manifest.json', 'package.json', 'advisories-accepted.json', 'sources.json', 'README.md']);
  for (const [name, pkg] of Object.entries(manifest.packages)) {
    if (!/^\d+\.\d+\.\d+/.test(pkg.version || '')) problems.push(`${name}: no version in the manifest`);
    for (const f of pkg.files || []) {
      expected.add(f.to);
      const p = join(vendorDir, f.to);
      if (!existsSync(p)) {
        problems.push(`vendor/${f.to} is missing (${name} ${pkg.version}: ${f.from})`);
        continue;
      }
      const got = sha256(readFileSync(p));
      if (got !== f.sha256) problems.push(`vendor/${f.to} is not ${name} ${pkg.version}'s ${f.from}: SHA-256 ${got.slice(0, 16)}… but the manifest says ${String(f.sha256).slice(0, 16)}… — it was edited by hand or replaced; restore it with: node tools/vendor.mjs update ${name} --to ${pkg.version}`);
    }
    if (pkg.licenseFile) {
      expected.add(pkg.licenseFile);
      if (!existsSync(join(vendorDir, pkg.licenseFile))) problems.push(`vendor/${pkg.licenseFile} (the license of ${name}) is missing`);
    }
  }
  for (const f of readdirSync(vendorDir)) if (!expected.has(f)) problems.push(`vendor/${f} is not in the manifest — every file in vendor/ must come from a package listed in vendor/manifest.json`);
  const pj = join(vendorDir, 'package.json');
  if (!existsSync(pj)) problems.push('vendor/package.json is missing (node tools/vendor.mjs update writes it)');
  else if (JSON.stringify(JSON.parse(readFileSync(pj, 'utf8')).dependencies) !== JSON.stringify(vendorPackageJson(manifest).dependencies)) problems.push('vendor/package.json does not list the versions in vendor/manifest.json — run: node tools/vendor.mjs update (do not edit either file by hand; a Dependabot pull request that only bumps package.json needs that command too)');
  try {
    const readme = readFileSync(join(root, 'README.md'), 'utf8');
    if (!readme.includes(readmeVendorLine(manifest))) problems.push('README.md does not name the vendored versions in the manifest — run: node tools/vendor.mjs update');
  } catch {
    /* no README next to the tool: nothing to compare */
  }
  return problems;
}

// ---------------------------------------------------------------- npm --

class NetworkError extends Error {}

function npm(args, { cwd = root, allowFail = false } = {}) {
  try {
    return execFileSync(NPM, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32' });
  } catch (e) {
    const text = `${e.stdout || ''}${e.stderr || ''}`;
    if (/ENOTFOUND|EAI_AGAIN|ECONNREFUSED|ECONNRESET|ETIMEDOUT|network|ENETUNREACH|503|502/i.test(text) && !allowFail) throw new NetworkError(text.split('\n').find((l) => /npm (ERR|error)/.test(l)) || 'npm could not reach the registry');
    if (allowFail && e.stdout) return e.stdout; // `npm audit` exits 1 when it finds something; the report is on stdout
    if (e.code === 'ENOENT') throw new Error('npm was not found on the PATH — it comes with Node (https://nodejs.org).');
    throw new Error(text.trim().split('\n').slice(-6).join('\n') || e.message);
  }
}

const latestVersion = (name) => JSON.parse(npm(['view', name, 'version', '--json']));
const major = (v) => Number(String(v).split('.')[0]);
const cmp = (a, b) => {
  const [x, y] = [a, b].map((v) => String(v).split('-')[0].split('.').map(Number));
  for (let i = 0; i < 3; i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) < (y[i] || 0) ? -1 : 1;
  return 0;
};

/** Download name@version (npm checks its integrity against the registry) and unpack it; returns { dir, integrity }. */
function fetchPackage(name, version, work) {
  const dest = join(work, name.replace(/[^\w.-]/g, '_'));
  mkdirSync(dest, { recursive: true });
  const info = JSON.parse(npm(['pack', `${name}@${version}`, '--pack-destination', dest, '--json', '--ignore-scripts']))[0];
  execFileSync('tar', ['-xzf', join(dest, info.filename), '-C', dest]);
  return { dir: join(dest, 'package'), integrity: info.integrity };
}

// ------------------------------------------------------------- update --

export function update({ only = [], to = null, allowMajor = true, log = console.log } = {}) {
  const manifest = loadManifest();
  const names = Object.keys(manifest.packages).filter((n) => !only.length || only.includes(n));
  for (const n of only) if (!manifest.packages[n]) throw new Error(`${n} is not in vendor/manifest.json (known: ${Object.keys(manifest.packages).join(', ')})`);
  if (to && names.length !== 1) throw new Error('--to needs exactly one package name');
  const work = mkdtempSync(join(tmpdir(), 'pmb-vendor-'));
  const changes = [];
  try {
    for (const name of names) {
      const pkg = manifest.packages[name];
      let target = to || latestVersion(name);
      if (!to && !allowMajor && major(target) !== major(pkg.version)) {
        log(`  ${name}: ${pkg.version} kept — ${target} is a new major version (run without --no-major to take it)`);
        continue;
      }
      const intact = pkg.files.every((f) => existsSync(join(vendorDir, f.to)) && sha256(readFileSync(join(vendorDir, f.to))) === f.sha256);
      if (target === pkg.version && intact) {
        log(`  ${name}: ${pkg.version} is current`);
        continue;
      }
      const { dir, integrity } = fetchPackage(name, target, work);
      for (const f of pkg.files) {
        const src = join(dir, f.from);
        if (!existsSync(src)) throw new Error(`${name}@${target} has no ${f.from} — the package's layout changed; adjust "from" in vendor/manifest.json`);
        copyFileSync(src, join(vendorDir, f.to));
        f.sha256 = sha256(readFileSync(join(vendorDir, f.to)));
      }
      if (pkg.licenseFile) {
        const lic = readdirSync(dir).find((x) => /^licen[cs]e(\.md|\.txt)?$/i.test(x));
        if (lic) copyFileSync(join(dir, lic), join(vendorDir, pkg.licenseFile));
      }
      try {
        pkg.license = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).license || pkg.license;
      } catch {
        /* keep the recorded license */
      }
      const from = pkg.version;
      pkg.version = target;
      pkg.integrity = integrity;
      changes.push({ name, from, to: target, major: major(from) !== major(target), restored: from === target });
      log(`  ${name}: ${from === target ? `${target} restored` : `${from} → ${target}`}${major(from) !== major(target) ? '  (new major version — read its changelog)' : ''}`);
    }
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
  saveManifest(manifest);
  writeFileSync(join(vendorDir, 'package.json'), JSON.stringify(vendorPackageJson(manifest), null, 2) + '\n');
  // the one line in the README that names the versions
  const readmePath = join(root, 'README.md');
  if (existsSync(readmePath)) {
    const readme = readFileSync(readmePath, 'utf8');
    const next = readme.replace(/^vendor\/ {2,}.*$/m, readmeVendorLine(manifest));
    if (next !== readme) writeFileSync(readmePath, next);
  }
  return changes;
}

// -------------------------------------------------------------- audit --

function loadAccepted() {
  if (!existsSync(acceptedPath)) return [];
  const list = JSON.parse(readFileSync(acceptedPath, 'utf8')).accepted || [];
  const today = new Date().toISOString().slice(0, 10);
  return list.filter((a) => a && typeof a.id === 'string').map((a) => ({ ...a, expired: !!a.until && a.until < today }));
}

/** Advisories from an `npm audit --json` report, one entry per advisory. */
export function advisoriesFrom(report) {
  const out = new Map();
  for (const [name, v] of Object.entries(report?.vulnerabilities || {})) {
    for (const via of v.via || []) {
      if (typeof via !== 'object') continue; // a string names the package it came through; the advisory itself is listed under that package
      const id = (String(via.url || '').match(/GHSA-[\w-]+/) || [String(via.source || via.title)])[0];
      if (!out.has(id)) out.set(id, { id, package: via.name || name, severity: via.severity || v.severity || 'low', title: via.title || '', url: via.url || '', range: via.range || '', fix: v.fixAvailable && typeof v.fixAvailable === 'object' ? `${v.fixAvailable.name}@${v.fixAvailable.version}` : v.fixAvailable ? 'available' : 'none yet' });
    }
  }
  return [...out.values()].sort((a, b) => SEVERITIES.indexOf(b.severity) - SEVERITIES.indexOf(a.severity));
}

/** Advisories for the vendored versions (and what they bring with them, minus the optional extras the app does not ship). */
function auditVendored(manifest) {
  const work = mkdtempSync(join(tmpdir(), 'pmb-audit-'));
  try {
    writeFileSync(join(work, 'package.json'), JSON.stringify({ ...vendorPackageJson(manifest), name: 'pmb-audit' }));
    npm(['install', '--package-lock-only', '--ignore-scripts', '--omit=optional', '--no-audit', '--no-fund'], { cwd: work });
    return advisoriesFrom(JSON.parse(npm(['audit', '--json', '--omit=optional'], { cwd: work, allowFail: true })));
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

/** Advisories for the development tools (Playwright, the mock's socket.io): never shipped, so reported, not failed on. */
function auditDev() {
  if (!existsSync(join(root, 'package-lock.json'))) return null;
  try {
    return advisoriesFrom(JSON.parse(npm(['audit', '--json'], { allowFail: true })));
  } catch (e) {
    if (e instanceof NetworkError) throw e;
    return null;
  }
}

export function check({ level = 'low' } = {}) {
  const manifest = loadManifest();
  const problems = verify(manifest);
  const outdated = [];
  for (const [name, pkg] of Object.entries(manifest.packages)) {
    const latest = latestVersion(name);
    if (cmp(pkg.version, latest) < 0) outdated.push({ name, current: pkg.version, latest, major: major(latest) !== major(pkg.version) });
  }
  const accepted = loadAccepted();
  const all = auditVendored(manifest);
  const isAccepted = (a) => accepted.find((x) => x.id === a.id && !x.expired);
  const open = all.filter((a) => !isAccepted(a));
  const waived = all.filter(isAccepted).map((a) => ({ ...a, reason: isAccepted(a).reason || '', until: isAccepted(a).until || '' }));
  const blocking = open.filter((a) => SEVERITIES.indexOf(a.severity) >= SEVERITIES.indexOf(level));
  return { packages: Object.fromEntries(Object.entries(manifest.packages).map(([n, p]) => [n, p.version])), problems, outdated, advisories: open, blocking, accepted: waived, expiredAcceptances: accepted.filter((a) => a.expired).map((a) => a.id), dev: auditDev(), level };
}

export function reportMarkdown(r) {
  const lines = ['## Dependencies', ''];
  lines.push('| Library | Shipped | Latest |', '| --- | --- | --- |');
  for (const [name, version] of Object.entries(r.packages)) {
    const o = r.outdated.find((x) => x.name === name);
    lines.push(`| ${name} | ${version} | ${o ? `**${o.latest}**${o.major ? ' (major)' : ''}` : 'current'} |`);
  }
  lines.push('');
  if (r.problems.length) lines.push('### Vendored files', '', ...r.problems.map((p) => `- ❌ ${p}`), '');
  if (r.advisories.length) {
    lines.push(`### Security advisories for the shipped versions (${r.advisories.length})`, '', '| Severity | Package | Advisory | Affected | Fix |', '| --- | --- | --- | --- | --- |');
    for (const a of r.advisories) lines.push(`| ${a.severity} | ${a.package} | [${a.title.replace(/\|/g, '\\|') || a.id}](${a.url}) | ${a.range.replace(/\|/g, '\\|')} | ${a.fix} |`);
    lines.push('', 'Update with `node tools/vendor.mjs update`, run the tests, and release. An advisory that does not apply to how the app uses the library can be recorded in `vendor/advisories-accepted.json` with a reason and an end date.', '');
  } else lines.push('No open security advisories for the shipped library versions.', '');
  if (r.accepted.length) lines.push('### Accepted advisories', '', ...r.accepted.map((a) => `- ${a.id} (${a.package}, ${a.severity})${a.until ? ` until ${a.until}` : ''}: ${a.reason}`), '');
  if (r.expiredAcceptances.length) lines.push(`Acceptances past their end date (counted as open again): ${r.expiredAcceptances.join(', ')}`, '');
  if (r.dev?.length) lines.push(`### Development tools (not shipped): ${r.dev.length} advisor${r.dev.length === 1 ? 'y' : 'ies'}`, '', ...r.dev.slice(0, 20).map((a) => `- ${a.severity}: ${a.package} — [${a.title || a.id}](${a.url})`), '', 'Fix with `npm update` (or `npm audit fix`) and commit package-lock.json.', '');
  return lines.join('\n');
}

function printReport(r) {
  console.log('Vendored libraries:');
  for (const [name, version] of Object.entries(r.packages)) {
    const o = r.outdated.find((x) => x.name === name);
    console.log(`  ${name.padEnd(18)} ${version.padEnd(9)} ${o ? `→ ${o.latest} available${o.major ? ' (new major version)' : ''}` : 'current'}`);
  }
  if (r.problems.length) {
    console.log('\nVendored files that are not what the manifest says:');
    for (const p of r.problems) console.log(`  ✗ ${p}`);
  }
  if (r.advisories.length) {
    console.log(`\nSecurity advisories for the shipped versions (${r.advisories.length}):`);
    for (const a of r.advisories) console.log(`  ${a.severity.toUpperCase().padEnd(9)} ${a.package}: ${a.title}\n            ${a.url}  (affects ${a.range}; fix: ${a.fix})`);
  } else console.log('\nNo open security advisories for the shipped library versions.');
  if (r.accepted.length) {
    console.log('\nAccepted (vendor/advisories-accepted.json):');
    for (const a of r.accepted) console.log(`  ${a.id} ${a.package}${a.until ? ` until ${a.until}` : ''} — ${a.reason}`);
  }
  if (r.expiredAcceptances.length) console.log(`\nAcceptances past their end date, counted as open again: ${r.expiredAcceptances.join(', ')}`);
  if (r.dev?.length) console.log(`\nDevelopment tools (not shipped): ${r.dev.length} advisor${r.dev.length === 1 ? 'y' : 'ies'} — npm update, then commit package-lock.json\n${r.dev.slice(0, 8).map((a) => `  ${a.severity}: ${a.package} — ${a.title}`).join('\n')}`);
  if (r.outdated.length) console.log(`\nTo update: node tools/vendor.mjs update   (then: node tests/run.mjs && npm run test:e2e)`);
}

// ------------------------------------------------------------ sources --
// The app ships no code from these projects, but what it knows about the Portal's
// packets and the machine's API comes from them. When one of them changes, somebody
// should read the change against the file named in `usedIn`.

export const loadSources = () => JSON.parse(readFileSync(sourcesPath, 'utf8'));

/** Commits in each source since it was last reviewed: [{ repo, what, usedIn, reviewed, commits: [{ sha, date, title }], more, url, error }]. */
export async function sourcesReport({ fetchImpl = globalThis.fetch, token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN || '' } = {}) {
  const out = [];
  for (const src of loadSources().sources) {
    const q = new URLSearchParams({ since: `${src.reviewed}T23:59:59Z`, per_page: '30' });
    if (src.branch) q.set('sha', src.branch);
    if (src.path) q.set('path', src.path);
    const entry = { repo: src.repo, what: src.what, usedIn: src.usedIn, reviewed: src.reviewed, commits: [], more: false, url: `https://github.com/${src.repo}/commits/${src.branch || ''}?since=${src.reviewed}`, error: null };
    try {
      const ask = (auth) => fetchImpl(`https://api.github.com/repos/${src.repo}/commits?${q}`, { headers: { accept: 'application/vnd.github+json', 'user-agent': 'portal-met-bridge-vendor', ...(auth ? { authorization: `Bearer ${auth}` } : {}) } });
      let res = await ask(token);
      if (token && (res.status === 401 || res.status === 403)) res = await ask(''); // a token that is not for this repository: public data needs none
      if (!res.ok) throw new Error(`GitHub answered ${res.status}`);
      const list = await res.json();
      entry.commits = (Array.isArray(list) ? list : []).map((c) => ({ sha: String(c.sha || '').slice(0, 7), date: String(c.commit?.committer?.date || c.commit?.author?.date || '').slice(0, 10), title: String(c.commit?.message || '').split('\n')[0].slice(0, 120) }));
      entry.more = entry.commits.length >= 30;
    } catch (e) {
      entry.error = e?.message || String(e);
    }
    out.push(entry);
  }
  return out;
}

export function sourcesMarkdown(report) {
  const changed = report.filter((r) => r.commits.length);
  const lines = ['## Upstream projects', ''];
  if (!changed.length) lines.push(`No changes since the last review in ${report.filter((r) => !r.error).map((r) => r.repo).join(', ')}.`, '');
  for (const r of changed) {
    lines.push(`### [${r.repo}](${r.url}) — ${r.commits.length}${r.more ? '+' : ''} commit${r.commits.length === 1 ? '' : 's'} since ${r.reviewed}`, '', `Gives the app: ${r.what}. Read the changes against \`${r.usedIn}\`.`, '', ...r.commits.slice(0, 12).map((c) => `- ${c.date} \`${c.sha}\` ${c.title.replace(/[<>|]/g, ' ')}`), r.commits.length > 12 ? `- … ${r.commits.length - 12} more` : '', '');
  }
  for (const r of report.filter((x) => x.error)) lines.push(`- ${r.repo}: could not be read (${r.error})`);
  if (changed.length) lines.push('', 'When they have been read (and the app adjusted if needed): `node tools/vendor.mjs sources --record`, commit vendor/sources.json.');
  return lines.join('\n');
}

function recordSources(only = []) {
  const doc = loadSources();
  const today = new Date().toISOString().slice(0, 10);
  for (const s of doc.sources) if (!only.length || only.includes(s.repo)) { s.reviewed = today; s.head = null; }
  writeFileSync(sourcesPath, JSON.stringify(doc, null, 2) + '\n');
  return today;
}

// ---------------------------------------------------------------- cli --

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const [cmd, ...rest] = process.argv.slice(2);
  const flag = (name) => rest.includes(name);
  const valueOf = (name) => (rest.includes(name) ? rest[rest.indexOf(name) + 1] : undefined);
  const positional = rest.filter((a, i) => !a.startsWith('--') && !['--to', '--level', '--summary'].includes(rest[i - 1]));
  try {
    if (cmd === 'verify') {
      const problems = verify();
      if (problems.length) {
        for (const p of problems) console.error(`✗ ${p}`);
        process.exit(1);
      }
      console.log(`vendor/ matches the manifest (${Object.entries(loadManifest().packages).map(([n, p]) => `${n} ${p.version}`).join(', ')}).`);
    } else if (cmd === 'update') {
      console.log('Updating vendor/ from npm:');
      const changes = update({ only: positional, to: valueOf('--to') || null, allowMajor: !flag('--no-major') });
      const problems = verify();
      if (problems.length) {
        for (const p of problems) console.error(`✗ ${p}`);
        process.exit(1);
      }
      console.log(changes.length ? `\n${changes.length} librar${changes.length === 1 ? 'y' : 'ies'} changed. Now run the tests (node tests/run.mjs && npm run test:e2e), look at a PDF report and a zip export, and commit vendor/ and README.md.` : '\nNothing to update.');
      if (flag('--json')) console.log(JSON.stringify(changes));
    } else if (cmd === 'check') {
      const level = valueOf('--level') || 'low';
      if (!SEVERITIES.includes(level)) throw new Error(`--level takes one of ${SEVERITIES.slice(1).join(', ')}`);
      const r = check({ level });
      if (flag('--json')) console.log(JSON.stringify(r, null, 2));
      else printReport(r);
      const summary = valueOf('--summary');
      if (summary) appendFileSync(summary, reportMarkdown(r) + '\n');
      if (r.problems.length || r.blocking.length) process.exit(1);
      if (flag('--fail-outdated') && r.outdated.length) process.exit(3);
    } else if (cmd === 'sources') {
      if (flag('--record')) {
        console.log(`Marked ${positional.length ? positional.join(', ') : 'every source'} as reviewed on ${recordSources(positional)}. Commit vendor/sources.json.`);
      } else {
        const report = await sourcesReport();
        if (report.every((r) => r.error)) throw new NetworkError(report[0]?.error || 'GitHub could not be reached');
        if (flag('--json')) console.log(JSON.stringify(report, null, 2));
        else console.log(sourcesMarkdown(report).replace(/^#+ /gm, '').replace(/`/g, ''));
        const summary = valueOf('--summary');
        if (summary) appendFileSync(summary, sourcesMarkdown(report) + '\n');
        if (flag('--fail-changed') && report.some((r) => r.commits.length)) process.exit(3);
      }
    } else {
      console.log('usage: node tools/vendor.mjs verify | check [--level high] [--fail-outdated] [--json] [--summary file] | update [package] [--to version] [--no-major] | sources [--record] [--summary file] [--fail-changed]');
      process.exit(cmd ? 1 : 0);
    }
  } catch (e) {
    if (e instanceof NetworkError) {
      console.error(`Could not reach ${cmd === 'sources' ? 'GitHub' : 'the npm registry'}: ${e.message}`);
      process.exit(2);
    }
    console.error(e.message || e);
    process.exit(1);
  }
}
